const fs=require('fs'),vm=require('vm'),assert=require('assert'),path=require('path');
const scope={window:{}};vm.createContext(scope);
for(const file of ['versions.js','source-ranking.js'])vm.runInContext(fs.readFileSync(path.join(__dirname,'../mobile',file),'utf8'),scope);
const V=scope.window.StarlightVersions,R=scope.window.StarlightRanking.assess;
const original={name:'电影英语版',area:'美国'},dub={name:'电影国语版',area:'美国'},unknown={name:'电影',area:'美国'};
const fast={ok:true,mbps:20,connectMs:300,variation:.1,declaredHeight:1080,declaredBandwidth:6000000};
const score=(r,e,h)=>R(r,e,h).score;
assert(score(original,fast)>score(dub,{...fast,mbps:50}),'Original wins among fluent streams');
assert(score(dub,fast)>score(original,{...fast,mbps:1}),'Playable dubbed beats slow original');
assert(score(unknown,null)>score(original,{ok:false}),'Untested is not failed');
assert(score(unknown,fast)>score(original,fast,{failures:3}),'Repeated playback failures demote original');
assert(score(unknown,fast)>score(original,fast,{stalls:4}),'Stalling original demoted');
assert(score(unknown,fast)>score(original,fast,{ad:true}),'Reported ad source demoted');
assert(score(original,fast)>score(original,{...fast,declaredHeight:720,mbps:50}),'Fluent 1080 beats fluent 720');
assert(score(original,fast)>score(original,{...fast,declaredHeight:0}),'Unknown resolution not invented');
assert(score(original,{...fast,mbps:30})>score(original,fast),'Equal language and definition prefer faster');
assert.equal(R(original,{...fast,declaredBandwidth:20000000}).tier,1,'Bitrate headroom required');
assert.equal(R(original,{...fast,variation:.9}).tier,1,'Unstable samples demoted');
assert.equal(R(original,fast,{height:720}).resolution,'720P（实播）');
assert.equal(R(original,{...fast,declaredHeight:0}).resolution,'清晰度未知');
assert(V.priority({language:'日语',area:'日本'})>V.priority({language:'英语',area:'日本'}),'Foreign does not automatically mean original');
assert(V.priority({language:'粤语',area:'香港'})>V.priority({language:'普通话',area:'香港'}));
assert(V.priority({language:'普通话',area:'中国大陆'})>V.priority({language:'英语',area:'中国大陆'}));
assert.equal(V.priority({language:'国语 / 英语',area:'美国'}),0,'Mixed language uncertain');
assert.equal(V.priority({language:'英语',area:'美国 / 日本'}),0,'Co-production uncertain');
const report={passed:true,checks:18,policy:'usable streams first; original-language hints, resolution, then throughput; poor streams demoted'};
fs.writeFileSync(require('./test-report.cjs')('beta12-ranking-tests.json'),JSON.stringify(report,null,2));console.log(report);
